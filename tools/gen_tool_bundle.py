#!/usr/bin/env python3
"""Bundle the simulator's own source files into src/editor/sim-bundle.js.

The "Whole tool SVG" export needs the *text* of the simulator (HTML skeleton, CSS, KaTeX, the JavaScript) so it can write a
single self-contained .svg file. Browsers cannot read their own script files, so this generator embeds them as strings.
Run it after editing sim*.js / style.css (npm run gen); `npm test` checks the bundle is up to date.
"""
import base64, hashlib, json, os, re, sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
def read(p, mode='r'):
    with open(os.path.join(ROOT, p), mode, **({} if 'b' in mode else {'encoding': 'utf-8'})) as f:
        return f.read()

# KaTeX: keep only the fonts the simulator's equations use, inline them as data: URIs so the SVG needs no extra files
USED = ['Main-Regular', 'Main-Bold', 'Main-Italic', 'Math-Italic', 'AMS-Regular', 'Size1-Regular', 'Size2-Regular', 'Size3-Regular', 'Size4-Regular']
css = read('src/vendor/katex/katex.min.css')
def face(m):
    block = m.group(0)
    name = re.search(r'fonts/KaTeX_([\w-]+)\.woff2', block)
    if not name or name.group(1) not in USED:
        return ''
    data = base64.b64encode(read('src/vendor/katex/fonts/KaTeX_%s.woff2' % name.group(1), 'rb')).decode()
    return re.sub(r'url\([^)]*\)', 'url(data:font/woff2;base64,%s)' % data, block)
katex_css = re.sub(r'@font-face\{[^}]*\}', face, css)

files = {
    'css': read('src/editor/style.css'),
    'katexCss': katex_css,
    'katexJs': read('src/vendor/katex/katex.min.js'),
    'simCore': read('src/editor/sim-core.js'),
    'simExport': read('src/editor/sim-export.js'),
    'sim': read('src/editor/sim.js'),
}
digest = hashlib.sha256(''.join(files[k] for k in sorted(files)).encode()).hexdigest()[:16]
out = '/* GENERATED by tools/gen_tool_bundle.py - do not edit by hand (npm run gen). */\nwindow.SIM_BUNDLE = ' + \
      json.dumps({**files, 'digest': digest}, ensure_ascii=False, separators=(',', ':')) + ';\n'
path = os.path.join(ROOT, 'src/editor/sim-bundle.js')
if len(sys.argv) > 1 and sys.argv[1] == '--check':
    cur = open(path, encoding='utf-8').read() if os.path.exists(path) else ''
    if cur != out:
        print('sim-bundle.js is out of date: run  npm run gen'); sys.exit(1)
    print('sim-bundle.js is up to date (%s)' % digest); sys.exit(0)
open(path, 'w', encoding='utf-8').write(out)
print('sim-bundle.js: %d KB, digest %s' % (len(out) // 1024, digest))
